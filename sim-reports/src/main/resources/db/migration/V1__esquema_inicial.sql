-- Esquema inicial (spec 04). Lo aplica Flyway; Hibernate solo lo valida
-- (spring.jpa.hibernate.ddl-auto=validate).

CREATE TABLE plantilla_config (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version        INTEGER                     NOT NULL,
    ruta_archivo   VARCHAR(1024)               NOT NULL,
    -- JSON serializado por el servicio; text (no oid, no jsonb): se lee y
    -- escribe entero, nunca se consulta por dentro.
    mapeo_columnas TEXT                        NOT NULL,
    activa         BOOLEAN                     NOT NULL,
    fecha_creacion TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_plantilla_config_version UNIQUE (version),
    -- Solo una version activa a la vez. Restriccion de exclusion parcial y
    -- DIFERIDA: se comprueba al hacer commit, no en cada sentencia, para que
    -- el reemplazo de la plantilla activa funcione sin importar el orden en
    -- que Hibernate emita el INSERT de la nueva y el UPDATE de la anterior
    -- (Hibernate ejecuta los INSERT antes que los UPDATE al hacer flush).
    CONSTRAINT ex_plantilla_config_una_activa
        EXCLUDE (activa WITH =) WHERE (activa) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE reporte_generado (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha                  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    plantilla_version_id   BIGINT                      NOT NULL
        CONSTRAINT fk_reporte_generado_plantilla REFERENCES plantilla_config (id),
    archivos_entrada       TEXT                        NOT NULL,
    ruta_archivo_resultado VARCHAR(1024)               NOT NULL,
    lineas_no_encontradas  TEXT                        NOT NULL,
    avisos                 TEXT                        NOT NULL
);

CREATE INDEX ix_reporte_generado_plantilla ON reporte_generado (plantilla_version_id);
CREATE INDEX ix_reporte_generado_fecha ON reporte_generado (fecha);
