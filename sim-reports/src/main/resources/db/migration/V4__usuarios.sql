-- Fase 4 punto 2 (spec 12, D-024/D-026): usuarios con contraseña (BCrypt) y rol.
-- nombre_usuario se guarda en minúsculas; la unicidad es sobre ese valor.
CREATE TABLE usuario (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario        VARCHAR(50)                 NOT NULL,
    nombre_completo       VARCHAR(100)                NOT NULL,
    password_hash         VARCHAR(100)                NOT NULL,
    password_actualizado  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- Sube cada vez que cambia la contraseña: cierra las sesiones abiertas.
    version_credenciales  INTEGER                     NOT NULL,
    rol                   VARCHAR(20)                 NOT NULL,
    activo                BOOLEAN                     NOT NULL,
    debe_cambiar_password BOOLEAN                     NOT NULL,
    intentos_fallidos     INTEGER                     NOT NULL,
    bloqueado_hasta       TIMESTAMP(6) WITH TIME ZONE,
    fecha_creacion        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ultimo_acceso         TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ux_usuario_nombre UNIQUE (nombre_usuario),
    CONSTRAINT ck_usuario_nombre_minusculas CHECK (nombre_usuario = lower(nombre_usuario)),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('SUPERADMIN', 'USUARIO'))
);
